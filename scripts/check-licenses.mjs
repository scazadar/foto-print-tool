/**
 * Checks that every production dependency (server) and every package bundled
 * into the web app is under a licence compatible with AGPL-3.0-or-later, and
 * writes THIRD_PARTY_LICENSES.md.
 *
 *   node scripts/check-licenses.mjs           # check and write the file
 *   node scripts/check-licenses.mjs --check   # check only, fail if the file is outdated
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

// SPDX identifiers that may be combined with AGPL-3.0-or-later
const ALLOWED = new Set([
  'MIT', 'MIT-0', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'Zlib', 'BlueOak-1.0.0',
  'CC0-1.0', 'Unlicense', 'Python-2.0', 'BSL-1.0', 'MPL-2.0',
  'LGPL-2.1', 'LGPL-2.1-only', 'LGPL-2.1-or-later', 'LGPL-3.0', 'LGPL-3.0-only', 'LGPL-3.0-or-later',
  'GPL-3.0', 'GPL-3.0-only', 'GPL-3.0-or-later', 'AGPL-3.0', 'AGPL-3.0-only', 'AGPL-3.0-or-later',
]);

// packages whose package.json lacks a proper SPDX field (checked by hand)
const OVERRIDES = {};

/** Is an SPDX expression acceptable? OR: one side suffices, AND: both sides needed. */
function allowed(expr) {
  const e = expr.trim().replace(/^\((.*)\)$/, '$1');
  if (/ OR /i.test(e)) return e.split(/ OR /i).some(allowed);
  if (/ AND /i.test(e)) return e.split(/ AND /i).every(allowed);
  return ALLOWED.has(e.replace(/[()]/g, '').trim());
}

function licenseOf(pkg) {
  if (OVERRIDES[pkg.name]) return OVERRIDES[pkg.name];
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}

function prodPackages(dir) {
  const out = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { cwd: dir, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return out.split('\n').filter((p) => p && p !== dir && p.includes('node_modules'));
}

const seen = new Map();
function add(dirs, usedBy) {
  for (const d of dirs) {
    const pj = path.join(d, 'package.json');
    if (!fs.existsSync(pj)) continue;
    const pkg = JSON.parse(fs.readFileSync(pj, 'utf8'));
    const key = `${pkg.name}@${pkg.version}`;
    if (seen.has(key)) {
      seen.get(key).usedBy.add(usedBy);
      continue;
    }
    seen.set(key, { name: pkg.name, version: pkg.version, license: licenseOf(pkg), homepage: pkg.homepage ?? pkg.repository?.url ?? pkg.repository ?? '', usedBy: new Set([usedBy]) });
  }
}

add(prodPackages(path.join(root, 'server')), 'server');
// the web app ships only what Vite bundles: svelte and its runtime dependencies
const webDir = path.join(root, 'web');
const bundled = ['svelte'];
const webDirs = [];
const visit = (name, base) => {
  const d = path.join(base, 'node_modules', name);
  const dir = fs.existsSync(d) ? d : path.join(webDir, 'node_modules', name);
  if (!fs.existsSync(dir) || webDirs.includes(dir)) return;
  webDirs.push(dir);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir);
};
for (const b of bundled) visit(b, webDir);
add(webDirs, 'web');

const list = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const bad = list.filter((p) => !allowed(p.license));
if (bad.length) {
  console.error('Licences not compatible with AGPL-3.0-or-later (or unknown):');
  for (const p of bad) console.error(`  ${p.name}@${p.version}: ${p.license}`);
  process.exit(1);
}

const counts = {};
for (const p of list) counts[p.license] = (counts[p.license] ?? 0) + 1;
const md = [
  '# Third-party licences',
  '',
  'Generated by `node scripts/check-licenses.mjs`. Fotodruck itself is licensed under AGPL-3.0-or-later (see LICENSE).',
  'The Docker image additionally contains Debian packages (fonts-dejavu, ca-certificates) under their own licences.',
  'The prebuilt libvips binaries bundled with sharp (@img/sharp-libvips-*) are licensed under LGPL-3.0-or-later; libheif-js is LGPL-3.0.',
  '',
  '## Summary',
  '',
  '| Licence | Packages |',
  '| --- | --- |',
  ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`),
  '',
  '## Packages',
  '',
  '| Package | Version | Licence | Used by |',
  '| --- | --- | --- | --- |',
  ...list.map((p) => `| ${p.name} | ${p.version} | ${p.license} | ${[...p.usedBy].join(', ')} |`),
  '',
].join('\n');

const target = path.join(root, 'THIRD_PARTY_LICENSES.md');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== md) {
    console.error('THIRD_PARTY_LICENSES.md is outdated: run `node scripts/check-licenses.mjs`.');
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, md);
}
console.log(`${list.length} packages checked, all compatible with AGPL-3.0-or-later.`);
